import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import CmsWorkspace from './index.jsx'

vi.mock('../../data/msbmCatalog.js', () => ({ universities: [{ slug: 'test-university', name: 'Test University', location: 'United Kingdom', summary: 'University introduction', about: 'University profile', focus: ['Business'] }], countries: [{ slug: 'united-kingdom', name: 'United Kingdom', currency: 'GBP' }], locations: [], categories: [{ slug: 'masters-degree', name: 'Master’s Degree', description: 'Master’s programmes' }], specializations: [], courses: [{ slug: 'test-course', title: 'Test programme', description: 'Programme introduction', longDescription: 'Course content', university: 'Test University', level: 'Master’s Degree', modules: [['Research methods', 'Academic research']], entry: ['An undergraduate degree'], gettingStarted: [{ title: 'Upload documents', description: 'Provide qualifications and references.' }] }] }))
vi.mock('../../data/msbmContentPages.json', () => ({ default: [] }))

beforeAll(() => {
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', '') }
  HTMLDialogElement.prototype.close = function () { this.removeAttribute('open') }
})
afterEach(cleanup)

describe('CMS workspace', () => {
  it('preserves application-step descriptions while editing a programme', () => {
    render(<CmsWorkspace initialView="programmes" />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Test programme' }))
    let editor = screen.getByRole('dialog')
    expect(within(editor).getByLabelText('Step 1 title')).toHaveValue('Upload documents')
    expect(within(editor).getByLabelText('Step 1 description')).toHaveValue('Provide qualifications and references.')
    fireEvent.change(within(editor).getByLabelText('Step 1 description'), { target: { value: 'Provide degree certificates and references.' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save changes' }))
    fireEvent.click(screen.getByRole('button', { name: 'Edit Test programme' }))
    editor = screen.getByRole('dialog')
    expect(within(editor).getByLabelText('Step 1 description')).toHaveValue('Provide degree certificates and references.')
    fireEvent.click(within(editor).getByRole('button', { name: 'Preview content' }))
    expect(within(editor).getByText('Upload documents — Provide degree certificates and references.')).toBeInTheDocument()
    expect(editor).not.toHaveTextContent('[object Object]')
  })

  it('filters content, renders an empty state and restores the inventory', () => {
    render(<CmsWorkspace initialView="pages" />)
    fireEvent.change(screen.getByRole('searchbox'), { target: { value: 'no matching item' } })
    expect(screen.getByRole('heading', { name: 'No matching content' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Clear filters' }))
    expect(screen.getByRole('button', { name: 'Edit Home' })).toBeInTheDocument()
  })

  it('validates duplicate paths and saves structured content in the session', () => {
    render(<CmsWorkspace initialView="pages" />)
    fireEvent.click(screen.getByRole('button', { name: 'New page' }))
    const editor = screen.getByRole('dialog')
    fireEvent.change(within(editor).getByLabelText(/^Title/), { target: { value: 'Admissions guidance' } })
    fireEvent.change(within(editor).getByLabelText(/^Main content/), { target: { value: '<script>Plain text content</script>' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save changes' }))
    expect(within(editor).getByText('Another content item already uses this page path.')).toBeInTheDocument()
    fireEvent.change(within(editor).getByLabelText(/^Page path/), { target: { value: '/admissions-guidance' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Preview content' }))
    expect(within(editor).getByText('<script>Plain text content</script>')).toBeInTheDocument()
    expect(editor.querySelector('script')).toBeNull()
    fireEvent.click(within(editor).getByRole('button', { name: 'Save changes' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Edit Admissions guidance' })).toBeInTheDocument()
    expect(screen.getByText('“Admissions guidance” saved in this session.')).toBeInTheDocument()
  })

  it('keeps unsaved content until discard is explicitly confirmed', () => {
    render(<CmsWorkspace initialView="pages" />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Home' }))
    const editor = screen.getByRole('dialog')
    fireEvent.change(within(editor).getByLabelText(/^Title/), { target: { value: 'Unsaved home title' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Close editor' }))
    expect(within(editor).getByText('Discard your unsaved changes?')).toBeInTheDocument()
    fireEvent.click(within(editor).getByRole('button', { name: 'Keep editing' }))
    expect(within(editor).getByLabelText(/^Title/)).toHaveValue('Unsaved home title')
    fireEvent.click(within(editor).getByRole('button', { name: 'Close editor' }))
    fireEvent.click(within(editor).getByRole('button', { name: 'Discard changes' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Edit Home' })).toBeInTheDocument()
  })

  it('reorders navigation and rejects external destinations', () => {
    render(<CmsWorkspace initialView="navigation" />)
    fireEvent.click(screen.getByRole('button', { name: 'Move Programmes up' }))
    const preview = screen.getByRole('navigation', { name: 'Draft menu preview' })
    expect(preview.firstElementChild).toHaveTextContent('Programmes')
    fireEvent.change(screen.getByLabelText('Destination', { selector: '#nav-programmes-path' }), { target: { value: 'javascript:alert(1)' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save navigation' }))
    expect(screen.getByRole('alert')).toHaveTextContent('valid local path')
  })

  it('prevents duplicate partner slugs and supports archive and restore', () => {
    render(<CmsWorkspace initialView="universities" />)
    fireEvent.click(screen.getByRole('button', { name: 'New partner' }))
    const editor = screen.getByRole('dialog')
    fireEvent.change(within(editor).getByLabelText('Institution name *'), { target: { value: 'Another university' } })
    fireEvent.change(within(editor).getByLabelText('URL slug *'), { target: { value: 'test-university' } })
    fireEvent.change(within(editor).getByLabelText('Short introduction *'), { target: { value: 'Partner profile' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save partner' }))
    expect(within(editor).getByRole('alert')).toHaveTextContent('already uses this URL slug')
    fireEvent.change(within(editor).getByLabelText('URL slug *'), { target: { value: 'another-university' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save partner' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Archive Another university' }))
    expect(screen.getByRole('button', { name: 'Restore Another university' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Restore Another university' }))
    expect(screen.getByText('“Another university” restored as a draft.')).toBeInTheDocument()
  })

  it('requires testimonial approval before a published status can be saved', () => {
    render(<CmsWorkspace initialView="testimonials" />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Learner story template' }))
    const editor = screen.getByRole('dialog')
    fireEvent.change(within(editor).getByLabelText('Editorial status'), { target: { value: 'Published' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save testimonial' }))
    expect(within(editor).getByRole('alert')).toHaveTextContent('Obtain approval')
    fireEvent.change(within(editor).getByLabelText('Approval *'), { target: { value: 'Approved for display' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save testimonial' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })

  it('saves a revision and restores it as a draft through the publishing queue', () => {
    render(<CmsWorkspace initialView="pages" />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Home' }))
    fireEvent.change(screen.getByRole('dialog').querySelector('input'), { target: { value: 'Updated Home' } })
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Save changes' }))
    fireEvent.click(screen.getByRole('button', { name: 'Publishing & revisions' }))
    fireEvent.click(screen.getByRole('button', { name: 'Revision history for Updated Home' }))
    fireEvent.click(screen.getByRole('button', { name: 'Restore as draft' }))
    expect(screen.getByText('A previous version of “Home” restored as a draft.')).toBeInTheDocument()
    const row = screen.getByRole('button', { name: 'Home', exact: true }).closest('tr')
    expect(within(row).getByText('Draft')).toBeInTheDocument()
  })

  it('configures form fields and rejects unsafe settings destinations', () => {
    render(<CmsWorkspace initialView="forms" />)
    fireEvent.click(screen.getByRole('button', { name: 'Add field' }))
    expect(screen.getByLabelText('Field 5 label')).toHaveValue('New field')
    fireEvent.click(screen.getByRole('button', { name: 'Remove field 5' }))
    expect(screen.queryByLabelText('Field 5 label')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Save form configuration' }))
    expect(screen.getByText('Form configuration saved in this session.')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Site settings' }))
    fireEvent.change(screen.getByLabelText('Contact page path'), { target: { value: '//outside.example' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save site settings' }))
    expect(screen.getByRole('alert')).toHaveTextContent('valid local destination paths')
  })

  it('adds typed page sections, validates their labels, and preserves them after saving', () => {
    render(<CmsWorkspace initialView="pages" />)
    fireEvent.click(screen.getByRole('button', { name: 'New page' }))
    const editor = screen.getByRole('dialog')
    fireEvent.change(within(editor).getByLabelText(/^Title/), { target: { value: 'Student community' } })
    fireEvent.change(within(editor).getByLabelText(/^Page path/), { target: { value: '/student-community' } })
    fireEvent.change(within(editor).getByLabelText(/^Main content/), { target: { value: 'Connect with learners.' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Add field / section' }))
    fireEvent.click(within(editor).getByRole('button', { name: 'Save changes' }))
    expect(within(editor).getByRole('alert')).toHaveTextContent('Every custom field or section needs a label')
    fireEvent.change(within(editor).getByLabelText('Section 1 label *'), { target: { value: 'Community benefits' } })
    fireEvent.change(within(editor).getByLabelText('Section 1 type'), { target: { value: 'List' } })
    fireEvent.change(within(editor).getByLabelText('Section 1 value · one item per line'), { target: { value: 'Study groups\nPeer support' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save changes' }))
    fireEvent.click(screen.getByRole('button', { name: 'Edit Student community' }))
    fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Preview content' }))
    expect(within(screen.getByRole('dialog')).getByText('Peer support')).toBeInTheDocument()
    expect(within(screen.getByRole('dialog')).getByRole('heading', { name: 'Community benefits' })).toBeInTheDocument()
  })

  it('edits full programme metadata and validates module lecture counts', () => {
    render(<CmsWorkspace initialView="programmes" />)
    fireEvent.click(screen.getByRole('button', { name: 'Edit Test programme' }))
    const editor = screen.getByRole('dialog')
    expect(within(editor).getByLabelText('Programme slug')).toHaveValue('test-course')
    expect(within(editor).getByLabelText('Module 1 title')).toHaveValue('Research methods')
    fireEvent.change(within(editor).getByLabelText('Module 1 lecture count'), { target: { value: '-1' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save changes' }))
    expect(within(editor).getByRole('alert')).toHaveTextContent('non-negative whole numbers')
    fireEvent.change(within(editor).getByLabelText('Module 1 lecture count'), { target: { value: '8' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Add Lesson' }))
    fireEvent.change(within(editor).getByLabelText('Lesson 1 title'), { target: { value: 'Research ethics' } })
    fireEvent.change(within(editor).getByLabelText('Library resources'), { target: { value: 'Academic journals and research resources.' } })
    fireEvent.click(within(editor).getByRole('button', { name: 'Save changes' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Edit Test programme' }))
    expect(within(screen.getByRole('dialog')).getByLabelText('Lesson 1 title')).toHaveValue('Research ethics')
    expect(within(screen.getByRole('dialog')).getByLabelText('Module 1 lecture count')).toHaveValue('8')
  })

  it('manages footer columns, adds links and undoes removal', () => {
    render(<CmsWorkspace initialView="navigation" />)
    fireEvent.change(screen.getByLabelText('Menu area'), { target: { value: 'Footer' } })
    expect(screen.getAllByLabelText('Footer column').length).toBeGreaterThan(20)
    fireEvent.click(screen.getByRole('button', { name: 'Add menu item' }))
    const row = screen.getByRole('button', { name: 'Remove New link' }).closest('.cms-nav-item')
    fireEvent.change(within(row).getByLabelText('Menu label'), { target: { value: 'Learner help' } })
    fireEvent.change(within(row).getByLabelText('Destination'), { target: { value: '/contact' } })
    fireEvent.change(within(row).getByLabelText('Footer column'), { target: { value: 'Support' } })
    fireEvent.click(screen.getByRole('button', { name: 'Remove Learner help' }))
    expect(screen.queryByRole('button', { name: 'Remove Learner help' })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Undo removal' }))
    expect(screen.getByRole('button', { name: 'Remove Learner help' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Save navigation' }))
    expect(screen.getByText('Navigation saved in this session.')).toBeInTheDocument()
  }, 30000)
})
