function applyReplacements(value, replacements) {
  return replacements.reduce((text, [from, to]) => text.split(from).join(to), value)
}

function applyContentReplacements(markup, replacements) {
  const withRoutes = applyReplacements(markup, routeLinks)
  const withText = withRoutes.replace(/>([^<]+)</g, (match, text) => `>${applyReplacements(text, replacements)}<`)
  return withText.replace(/\b(alt|title|aria-label)="([^"]*)"/g, (match, attribute, value) => `${attribute}="${applyReplacements(value, replacements)}"`)
}

function makePage(source, key, title, description) {
  const replacements = [...common, ...(pageCopy[key] || [])]
  let body = applyContentReplacements(source.body, replacements)
  body = applyContentReplacements(body, finalCleanup)
  body = applyReplacements(body, structuralCopy)
  if (key === 'contact') {
    body = body.replace(
      /https:\/\/www\.google\.com\/maps\/embed\?pb=[^"]+/,
      'https://www.google.com/maps?q=Tay%20House%20300%20Bath%20Street%20Glasgow&output=embed',
    )
  }
  return {
    ...source,
    title,
    description,
    body,
  }
}

